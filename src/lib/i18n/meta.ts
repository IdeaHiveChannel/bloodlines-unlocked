function toLocale(params: { locale?: string } | undefined): Locale {
  return isLocale(params?.locale) ? params.locale : "en";
}

/**
 * Builds locale-aware head metadata for a static route. Malayalam copy comes
 * from `metaMl`, keyed by the canonical English path; English is the fallback.
 */
export function localeHead(
  params: { locale?: string } | undefined,
  path: string,
  en: MetaCopy & { ogType?: string; scripts?: HeadScript[] },
) {
  const locale = toLocale(params);
  const ml = metaMl[path];
  const copy: MetaCopy = locale === "ml" && ml ? ml : en;
  const url = `${SITE}${locale === "ml" ? (path === "/" ? "/ml" : `/ml${path}`) : path}`;

  return {
    meta: [
      { title: copy.title },
      { name: "description", content: copy.description },
      { property: "og:title", content: copy.ogTitle ?? copy.title },
      { property: "og:description", content: copy.ogDescription ?? copy.description },
      { property: "og:type", content: en.ogType ?? "website" },
      { property: "og:url", content: url },
      { property: "og:locale", content: locale === "ml" ? "ml_IN" : "en_IN" },
      { name: "twitter:card", content: "summary_large_image" },
      { property: "og:image", content: `${SITE}/og-card.jpg` },
      { name: "twitter:image", content: `${SITE}/og-card.jpg` },
    ],
    links: [{ rel: "canonical", href: url }],
    ...(en.scripts ? { scripts: en.scripts } : {}),
  };
}
